def norm(s: str) -> str:
    s = unicodedata.normalize("NFKD", s).encode("ASCII", "ignore").decode().lower()
    return re.sub(r"[^a-z0-9]+", "", s)


def to_int(s, default=50) -> int:
    if s is None or s == "" or s == "nan":
        return default
    try:
        return int(float(s))
    except (TypeError, ValueError):
        return default


