def download_year(year: int) -> Path:
    """The cache should already be populated from previous ingests."""
    path = FIFA_CACHE / f"FIFA{year}_official_data.csv"
    if not path.exists():
        raise FileNotFoundError(
            f"Missing FIFA cache: {path}. Run tools/ingest_pl_to_ucl.py once to populate."
        )
    return path


def ingest_fifa(accum: dict[tuple[str, str], dict]) -> int:
    """For every FIFA17-23 player at a Swiss club, accumulate the best entry."""
    added = 0
    for year in sorted(SEASONS.keys()):
        path = download_year(year)
        season = SEASONS[year]
        with open(path, "r", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                club = (row.get("Club") or "").strip()
                club_id = FIFA_CLUB_TO_SWISS.get(club)
                if not club_id:
                    continue
                best_pos = (row.get("Best Position") or "").strip()
                pos = POS_MAP.get(best_pos)
                if not pos:
                    continue
                ovr = to_int(row.get("Overall"))
                if ovr < MIN_OVR:
                    continue
                name = (row.get("Name") or "").strip()
                if not name:
                    continue
                nationality = (row.get("Nationality") or "").strip()
                key = (norm(name), club_id)
                existing = accum.get(key)
                if existing is None or ovr > existing["prime_rating"]:
                    accum[key] = {
                        "name": name,
                        "position": pos,
                        "prime_rating": ovr,
                        "_first_year": int(season.split("/")[0]),
                        "_last_year": int("20" + season.split("/")[1]),
                        "nationality": nationality,
                        "club": club_id,
                    }
                    if existing is None:
                        added += 1
                else:
                    fy = int(season.split("/")[0])
                    ly = int("20" + season.split("/")[1])
                    existing["_first_year"] = min(existing["_first_year"], fy)
                    existing["_last_year"] = max(existing["_last_year"], ly)
    return added


def add_legends(accum: dict[tuple[str, str], dict]) -> int:
    """Merge in hand-curated legends. Idempotent via the same key."""
    added = 0
    for club_id, entries in LEGENDS.items():
        for name, pos, ovr, years, nat in entries:
            key = (norm(name), club_id)
            if key in accum:
                # Already covered by FIFA — bump rating if legend rating is higher
                if accum[key]["prime_rating"] < ovr:
                    accum[key]["prime_rating"] = ovr
                continue
            accum[key] = {
                "name": name,
                "position": pos,
                "prime_rating": ovr,
                "_legend_years": years,
                "nationality": nat,
                "club": club_id,
            }
            added += 1
    return added


def finalize(accum: dict[tuple[str, str], dict]) -> list[dict]:
    out = []
    for entry in accum.values():
        if "_legend_years" in entry:
            entry["career_years"] = entry.pop("_legend_years")
        else:
            fy = entry.pop("_first_year")
            ly = entry.pop("_last_year")
            entry["career_years"] = f"{fy}-{ly}"
        out.append(entry)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    accum: dict[tuple[str, str], dict] = {}

    print("Ingesting FIFA17-23 Swiss clubs...")
    fifa_count = ingest_fifa(accum)
    print(f"  → {fifa_count} unique players from FIFA cache")

    print("\nMerging hand-curated legends...")
    legend_count = add_legends(accum)
    print(f"  → {legend_count} legends added on top")

    players = finalize(accum)
    print(f"\nTotal: {len(players)} Swiss players")

    from collections import Counter
    per_club = Counter(p["club"] for p in players)
    print("\nPer-club roster size:")
    clubs = json.loads(SWISS_CLUBS.read_text())
    for c in sorted(clubs, key=lambda x: -per_club.get(x["id"], 0)):
        n = per_club.get(c["id"], 0)
        print(f"  {c['name']:30} {n:3d}")

    if args.dry_run:
        print("\n--dry-run, not writing.")
        return 0

    # Sort: by club, then rating desc, then name
    players.sort(key=lambda x: (x["club"], -x["prime_rating"], x["name"]))
    SWISS_PLAYERS.write_text(json.dumps(players, indent=2, ensure_ascii=False) + "\n")
    print(f"\nWrote {len(players)} players to {SWISS_PLAYERS.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
